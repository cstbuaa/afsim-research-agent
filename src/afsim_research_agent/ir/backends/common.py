"""Helpers shared by backend compilers."""

from __future__ import annotations

from typing import Any

_SYMBOL = {"eq": "==", "ne": "!=", "lt": "<", "lte": "<=", "gt": ">", "gte": ">="}


def trees_for_role(ir: dict[str, Any], role: dict[str, Any]) -> list[str]:
    """Tree ids reachable from a role (state trees, root tree, subtrees), in a stable order."""
    trees = {t["id"]: t for t in ir["trees"]}
    roots: list[str] = []
    machine = role.get("state_machine")
    if machine:
        roots += [s["tree"] for s in machine["states"] if s.get("tree")]
    if role.get("root_tree"):
        roots.append(role["root_tree"])
    seen: list[str] = []
    while roots:
        tree_id = roots.pop(0)
        if tree_id in seen or tree_id not in trees:
            continue
        seen.append(tree_id)
        stack = [trees[tree_id]["root"]]
        while stack:
            node = stack.pop(0)
            if node["type"] == "subtree":
                roots.append(node["tree"])
            stack += node.get("children", [])
    return seen


def describe_operand(op: dict[str, Any]) -> str:
    kind = op["kind"]
    if kind in ("literal", "id"):
        return repr(op["value"]) if isinstance(op["value"], str) else str(op["value"]).lower()
    if kind == "quantity":
        return f"{op['value']:g}"
    if kind == "parameter":
        return op["name"]
    if kind == "blackboard":
        return f"{op['board']}.{op['var']}"
    if kind == "memory":
        return f"memory.{op['name']}"
    if kind == "message_value":
        return f"{op['message']}.{op['field']}"
    if kind == "function":
        args = ", ".join(f"{k}={describe_operand(v)}" for k, v in op["arguments"].items())
        return f"{op['name']}({args})"
    if kind == "property":
        parts = [op["source"].removesuffix("_value")]
        if op.get("component"):
            parts.append(op["component"])
        parts.append(op["property"])
        text = ".".join(parts)
        if op.get("argument"):
            text += f"[{op['argument']}]"
        return text
    return kind


def describe_expr(expr: dict[str, Any]) -> str:
    op = expr["op"]
    if op in ("all", "any"):
        joiner = " and " if op == "all" else " or "
        return "(" + joiner.join(describe_expr(a) for a in expr["args"]) + ")"
    if op == "not":
        return f"not {describe_expr(expr['arg'])}"
    if op == "condition_ref":
        return expr["id"]
    if op == "literal":
        return "true" if expr["value"] else "false"
    if op == "compare":
        left, right = describe_operand(expr["left"]), describe_operand(expr["right"])
        return f"{left} {_SYMBOL[expr['operator']]} {right}"
    if op == "operand":
        return describe_operand(expr["operand"])
    return op


def header(kind: str, ir: dict[str, Any], template_version: str, comment: str) -> str:
    return (
        f"{comment} Generated by afsim-research-agent {kind} backend ({template_version}).\n"
        f"{comment} Model {ir['model']['id']} {ir['model']['version']}, IR {ir['ir_hash']}.\n"
        f"{comment} Deterministic output: edit behavior_spec.yaml, not this file.\n"
    )
